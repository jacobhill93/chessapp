const STROKE_TO_HEIGHT_RATIO = 1.5 / 45; // DESIGN.md: ~1.5px stroke on a 45-unit piece drawing

export const PIECE_SHAPES: Record<PieceType, PieceShape> = Object.fromEntries(
  (Object.keys(RAW) as PieceType[]).map((type) => {
    const { viewBox, transform, d } = RAW[type];
    const [, , , height] = viewBox;
    return [
      type,
      {
        viewBox: viewBox.join(" "),
        transform,
        d,
        strokeWidth: (STROKE_TO_HEIGHT_RATIO * height) / 0.1,
      },
    ];
  }),
) as Record<PieceType, PieceShape>;

export function Piece({
  type,
  color,
  className,
}: {
  type: PieceType;
  color: "w" | "b";
  className?: string;
}) {
  const shape = PIECE_SHAPES[type];

  return (
    <svg viewBox={shape.viewBox} className={className} aria-hidden="true">
      <g transform={shape.transform}>
        {color === "w" ? (
          <path
            d={shape.d}
            fill="var(--piece-white)"
            stroke="var(--piece-edge)"
            strokeWidth={shape.strokeWidth}
          />
        ) : (
          <path d={shape.d} fill="var(--piece-black)" stroke="none" />
        )}
      </g>
    </svg>
  );
}
